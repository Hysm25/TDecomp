static inline uint8_t read_sprite_rom_byte(const NES_State *nes, uint16_t addr) {
    if (nes->prg_rom[0x0C6C] != 0 || nes->prg_rom[0x0C6D] != 0) {
        return nes_read8(nes, addr);
    }
    if (addr >= 0x8C6C && addr < (uint16_t)(0x8C6C + sizeof(oamContentLookupAndSprites))) {
        return oamContentLookupAndSprites[addr - 0x8C6C];
    }
    return 0;
}

/*
 * Copies OAM staging buffer ($0200..$02FF) to PPU OAM via DMA ($4014).
 * Source address: $AB5E (main.asm lines 5486-5492).
 */
void copyOamStagingToOam(NES_State *nes) {
    if (!nes) return;
    nes_write8(nes, REG_OAMADDR, 0x00);
    nes_write8(nes, REG_OAMDMA, 0x02);
}

/*
 * Resets PPU scroll registers to (0, 0) and restores PPUCTRL from currentPpuCtrl.
 * Source address: $AA8A (main.asm lines 5356-5363).
 */
void copyCurrentScrollAndCtrlToPPU(NES_State *nes) {
    if (!nes) return;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes_write8(nes, REG_PPUCTRL, nes->ram[ADDR_CURRENT_PPU_CTRL]);
}

/*
 * Loads sprite data from ROM into OAM staging buffer ($0200) based on
 * spriteIndexInOamContentLookup ($A2), spriteXOffset ($A0), and spriteYOffset ($A1).
 * Source address: $8C27 (main.asm lines 1861-1903).
 */
void loadSpriteIntoOamStaging(NES_State *nes) {
    if (!nes) return;

    uint8_t spriteIndex = nes->ram[ADDR_SPRITE_INDEX_OAM];
    uint16_t lookup_addr = (uint16_t)(0x8C6C + (uint16_t)(spriteIndex * 2));
    uint8_t lo = read_sprite_rom_byte(nes, lookup_addr);
    uint8_t hi = read_sprite_rom_byte(nes, (uint16_t)(lookup_addr + 1));
    nes->ram[ADDR_GENERAL_COUNTER] = lo;
    nes->ram[ADDR_GENERAL_COUNTER2] = hi;

    uint16_t sprite_ptr = MAKE_WORD(lo, hi);
    uint8_t y_read = 0;
    uint8_t x_write = nes->ram[ADDR_OAM_STAGING_LENGTH];
    uint8_t y_off = nes->ram[ADDR_SPRITE_Y_OFFSET];
    uint8_t x_off = nes->ram[ADDR_SPRITE_X_OFFSET];

    while (true) {
        uint8_t b0 = read_sprite_rom_byte(nes, (uint16_t)(sprite_ptr + y_read));
        if (b0 == 0xFF) {
            break;
        }

        nes->ram[ADDR_OAM_STAGING + x_write] = (uint8_t)(b0 + y_off);
        x_write++;
        y_read++;

        nes->ram[ADDR_OAM_STAGING + x_write] = read_sprite_rom_byte(nes, (uint16_t)(sprite_ptr + y_read));
        x_write++;
        y_read++;

        nes->ram[ADDR_OAM_STAGING + x_write] = read_sprite_rom_byte(nes, (uint16_t)(sprite_ptr + y_read));
        x_write++;
        y_read++;

        uint8_t b3 = read_sprite_rom_byte(nes, (uint16_t)(sprite_ptr + y_read));
        nes->ram[ADDR_OAM_STAGING + x_write] = (uint8_t)(b3 + x_off);
        x_write++;
        y_read++;

        nes->ram[ADDR_OAM_STAGING_LENGTH] = (uint8_t)(nes->ram[ADDR_OAM_STAGING_LENGTH] + 4);
    }
}

/*
 * Updates background palette 2 ($3F08) and sprite palette 2 ($3F18)
 * according to player 1's level number modulo 10.
 * Source address: $9808 (main.asm lines 2833-2870).
 */
void updatePaletteForLevel(NES_State *nes) {
    if (!nes) return;

    uint8_t lvl = nes->ram[ADDR_P1_LEVEL_NUMBER];
    while (lvl >= 10) {
        lvl = (uint8_t)(lvl - 10);
    }
    uint8_t x = (uint8_t)(lvl << 2);

    nes->ram[ADDR_GENERAL_COUNTER] = 0;
    while (true) {
        nes_write8(nes, REG_PPUADDR, 0x3F);
        nes_write8(nes, REG_PPUADDR, (uint8_t)(0x08 + nes->ram[ADDR_GENERAL_COUNTER]));
        nes_write8(nes, REG_PPUDATA, colorTable[x]);
        nes_write8(nes, REG_PPUDATA, colorTable[x + 1]);
        nes_write8(nes, REG_PPUDATA, colorTable[x + 2]);
        nes_write8(nes, REG_PPUDATA, colorTable[x + 3]);
        nes->ram[ADDR_GENERAL_COUNTER] = (uint8_t)(nes->ram[ADDR_GENERAL_COUNTER] + 0x10);
        if (nes->ram[ADDR_GENERAL_COUNTER] == 0x20) {
            break;
        }
    }
}

/*
 * Render Mode 0: Legal screen and title screen scroll and control register update.
 * Masks currentPpuCtrl (& 0xFC) and resets scroll to (0, 0).
 * Source address: $82B1 (main.asm lines 636-646).
 */
void render_mode_legal_and_title_screens(NES_State *nes) {
    if (!nes) return;
    nes->ram[ADDR_CURRENT_PPU_CTRL] &= 0xFC;
    nes->ram[ADDR_PPU_SCROLL_X] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes->ram[ADDR_PPU_SCROLL_Y] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
}

/*
 * Render Mode 1: Menu screens scroll and control register update.
 * Masks currentPpuCtrl (& 0xFC), writes to PPUCTRL, and resets scroll to (0, 0).
 * Source address: $85DA (main.asm lines 1078-1091).
 */
void render_mode_menu_screens(NES_State *nes) {
    if (!nes) return;
    nes->ram[ADDR_CURRENT_PPU_CTRL] &= 0xFC;
    nes_write8(nes, REG_PPUCTRL, nes->ram[ADDR_CURRENT_PPU_CTRL]);
    nes->ram[ADDR_PPU_SCROLL_X] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes->ram[ADDR_PPU_SCROLL_Y] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
}

/*
 * Render Mode 4: Ending animation score rendering to PPU nametable.
 * Renders player 1 score ($208E) and Type B bonuses/total score ($20B0, $20D0, $212E).
 * Resets scroll to (0, 0).
 * Source address: $9F95 (main.asm lines 3975-4014).
 */
void render_mode_ending_animation(NES_State *nes) {
    if (!nes) return;

    nes_write8(nes, REG_PPUADDR, 0x20);
    nes_write8(nes, REG_PPUADDR, 0x8E);
    twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE + 2]);
    twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE + 1]);
    twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE]);

    if (nes->ram[ADDR_GAME_TYPE] != GAMETYPE_A) {
        nes_write8(nes, REG_PPUADDR, 0x20);
        nes_write8(nes, REG_PPUADDR, 0xB0);
        twoDigsToPPU(nes, nes->ram[ADDR_GENERAL_COUNTER4]);

        nes_write8(nes, REG_PPUADDR, 0x20);
        nes_write8(nes, REG_PPUADDR, 0xD0);
        twoDigsToPPU(nes, nes->ram[ADDR_GENERAL_COUNTER5]);

        nes_write8(nes, REG_PPUADDR, 0x21);
        nes_write8(nes, REG_PPUADDR, 0x2E);
        twoDigsToPPU(nes, nes->ram[ADDR_TOTAL_SCORE + 2]);
        twoDigsToPPU(nes, nes->ram[ADDR_TOTAL_SCORE + 1]);
        twoDigsToPPU(nes, nes->ram[ADDR_TOTAL_SCORE]);
    }

    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes_write8(nes, REG_PPUSCROLL, 0x00);
}

/*
 * Render Mode 3: Play and demo screen render handler.
 * Transfers dirty playfield rows or line clearing animation tiles to PPU nametables,
 * updates on-screen lines, level number, score, and piece statistics,
 * flashes the border palette and triggers SFX on tetris (4 completed lines),
 * and resets PPU scroll to (0, 0).
 * Source address: $94EE (main.asm lines 2457-2671).
 */
void render_mode_play_and_demo(NES_State *nes) {
    if (!nes) return;

    /* Player 1 playfield */
    if (nes->ram[ADDR_P1_PLAY_STATE] == PLAYSTATE_LINE_CLEAR_ANIM) {
        nes->ram[ADDR_PLAYFIELD_ADDR + 1] = HIGH_BYTE(ADDR_PLAYFIELD);
        nes->ram[ADDR_ROW_Y] = nes->ram[ADDR_P1_ROW_Y];
        nes->ram[ADDR_COMPLETED_ROW] = nes->ram[ADDR_P1_COMPLETED_ROW];
        nes->ram[ADDR_COMPLETED_ROW + 1] = nes->ram[ADDR_P1_COMPLETED_ROW + 1];
        nes->ram[ADDR_COMPLETED_ROW + 2] = nes->ram[ADDR_P1_COMPLETED_ROW + 2];
        nes->ram[ADDR_COMPLETED_ROW + 3] = nes->ram[ADDR_P1_COMPLETED_ROW + 3];
        nes->ram[ADDR_PLAY_STATE] = nes->ram[ADDR_P1_PLAY_STATE];

        updateLineClearingAnimation(nes);

        nes->ram[ADDR_P1_ROW_Y] = nes->ram[ADDR_ROW_Y];
        nes->ram[ADDR_P1_PLAY_STATE] = nes->ram[ADDR_PLAY_STATE];
        nes->ram[ADDR_P1_VRAM_ROW] = 0x00;
    } else {
        nes->ram[ADDR_VRAM_ROW] = nes->ram[ADDR_P1_VRAM_ROW];
        nes->ram[ADDR_PLAYFIELD_ADDR + 1] = HIGH_BYTE(ADDR_PLAYFIELD);
        copyPlayfieldRowToVRAM(nes);
        copyPlayfieldRowToVRAM(nes);
        copyPlayfieldRowToVRAM(nes);
        copyPlayfieldRowToVRAM(nes);
        nes->ram[ADDR_P1_VRAM_ROW] = nes->ram[ADDR_VRAM_ROW];
    }

    /* Player 2 playfield (if 2 players) */
    if (nes->ram[ADDR_NUMBER_OF_PLAYERS] == 2) {
        if (nes->ram[ADDR_P2_PLAY_STATE] == PLAYSTATE_LINE_CLEAR_ANIM) {
            nes->ram[ADDR_PLAYFIELD_ADDR + 1] = HIGH_BYTE(ADDR_PLAYFIELD_P2);
            nes->ram[ADDR_ROW_Y] = nes->ram[ADDR_P2_ROW_Y];
            nes->ram[ADDR_COMPLETED_ROW] = nes->ram[ADDR_P2_COMPLETED_ROW];
            nes->ram[ADDR_COMPLETED_ROW + 1] = nes->ram[ADDR_P2_COMPLETED_ROW + 1];
            nes->ram[ADDR_COMPLETED_ROW + 2] = nes->ram[ADDR_P2_COMPLETED_ROW + 2];
            nes->ram[ADDR_COMPLETED_ROW + 3] = nes->ram[ADDR_P2_COMPLETED_ROW + 3];
            nes->ram[ADDR_PLAY_STATE] = nes->ram[ADDR_P2_PLAY_STATE];

            updateLineClearingAnimation(nes);

            nes->ram[ADDR_P2_ROW_Y] = nes->ram[ADDR_ROW_Y];
            nes->ram[ADDR_P2_PLAY_STATE] = nes->ram[ADDR_PLAY_STATE];
            nes->ram[ADDR_P2_VRAM_ROW] = 0x00;
        } else {
            nes->ram[ADDR_VRAM_ROW] = nes->ram[ADDR_P2_VRAM_ROW];
            nes->ram[ADDR_PLAYFIELD_ADDR + 1] = HIGH_BYTE(ADDR_PLAYFIELD_P2);
            copyPlayfieldRowToVRAM(nes);
            copyPlayfieldRowToVRAM(nes);
            copyPlayfieldRowToVRAM(nes);
            copyPlayfieldRowToVRAM(nes);
            nes->ram[ADDR_P2_VRAM_ROW] = nes->ram[ADDR_VRAM_ROW];
        }
    }

    /* Lines rendering */
    if (nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] & RENDER_LINES) {
        if (nes->ram[ADDR_NUMBER_OF_PLAYERS] == 2) {
            nes_write8(nes, REG_PPUADDR, 0x20);
            nes_write8(nes, REG_PPUADDR, 0x68);
            nes_write8(nes, REG_PPUDATA, nes->ram[ADDR_P1_LINES + 1]);
            twoDigsToPPU(nes, nes->ram[ADDR_P1_LINES]);

            nes_write8(nes, REG_PPUADDR, 0x20);
            nes_write8(nes, REG_PPUADDR, 0x7A);
            nes_write8(nes, REG_PPUDATA, nes->ram[ADDR_P2_LINES + 1]);
            twoDigsToPPU(nes, nes->ram[ADDR_P2_LINES]);
        } else {
            nes_write8(nes, REG_PPUADDR, 0x20);
            nes_write8(nes, REG_PPUADDR, 0x73);
            nes_write8(nes, REG_PPUDATA, nes->ram[ADDR_P1_LINES + 1]);
            twoDigsToPPU(nes, nes->ram[ADDR_P1_LINES]);
        }
        nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] &= (uint8_t)~RENDER_LINES;
    }

    /* Level rendering (1-player mode only) */
    if ((nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] & RENDER_LEVEL) &&
        (nes->ram[ADDR_NUMBER_OF_PLAYERS] != 2)) {
        uint8_t lvl = nes->ram[ADDR_P1_LEVEL_NUMBER];
        uint8_t display_lvl = (lvl < sizeof(levelDisplayTable)) ? levelDisplayTable[lvl] : lvl;
        nes->ram[ADDR_GENERAL_COUNTER] = display_lvl;
        nes_write8(nes, REG_PPUADDR, 0x22);
        nes_write8(nes, REG_PPUADDR, 0xBA);
        twoDigsToPPU(nes, nes->ram[ADDR_GENERAL_COUNTER]);
        updatePaletteForLevel(nes);
        nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] &= (uint8_t)~RENDER_LEVEL;
    }

    /* Score rendering (1-player mode only) */
    if ((nes->ram[ADDR_NUMBER_OF_PLAYERS] != 2) &&
        (nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] & RENDER_SCORE)) {
        nes_write8(nes, REG_PPUADDR, 0x21);
        nes_write8(nes, REG_PPUADDR, 0x18);
        twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE + 2]);
        twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE + 1]);
        twoDigsToPPU(nes, nes->ram[ADDR_P1_SCORE]);
        nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] &= (uint8_t)~RENDER_SCORE;
    }

    /* Stats rendering (1-player mode only) */
    if ((nes->ram[ADDR_NUMBER_OF_PLAYERS] != 2) &&
        (nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] & RENDER_STATS)) {
        nes->ram[ADDR_TMP_CURRENT_PIECE] = 0;
        do {
            uint8_t piece = nes->ram[ADDR_TMP_CURRENT_PIECE];
            uint8_t x = (uint8_t)(piece << 1);
            nes_write8(nes, REG_PPUADDR, pieceToPpuStatAddr[x]);
            nes_write8(nes, REG_PPUADDR, pieceToPpuStatAddr[x + 1]);
            nes_write8(nes, REG_PPUDATA, nes->ram[ADDR_STATS_BY_TYPE + x + 1]);
            twoDigsToPPU(nes, nes->ram[ADDR_STATS_BY_TYPE + x]);
            nes->ram[ADDR_TMP_CURRENT_PIECE]++;
        } while (nes->ram[ADDR_TMP_CURRENT_PIECE] != 7);
        nes->ram[ADDR_OUT_OF_DATE_RENDER_FLAGS] &= (uint8_t)~RENDER_STATS;
    }

    /* Tetris flash, sound effect, and scroll reset */
    nes_write8(nes, REG_PPUADDR, 0x3F);
    nes_write8(nes, REG_PPUADDR, 0x0E);
    uint8_t flash_color = 0x00;
    if (nes->ram[ADDR_COMPLETED_LINES] == 4) {
        if ((nes->ram[ADDR_FRAME_COUNTER] & 0x03) == 0) {
            flash_color = 0x30;
            if ((nes->ram[ADDR_FRAME_COUNTER] & 0x07) == 0) {
                nes->ram[ADDR_SOUND_EFFECT_SLOT1_INIT] = SFX_TETRIS;
            }
        }
    }
    nes_write8(nes, REG_PPUDATA, flash_color);
    nes->ram[ADDR_PPU_SCROLL_X] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
    nes->ram[ADDR_PPU_SCROLL_Y] = 0;
    nes_write8(nes, REG_PPUSCROLL, 0x00);
}

/*
 * Master render dispatcher: jumps to corresponding render routine based on renderMode (0..4).
 * Source address: $804B (main.asm lines 290-296).
 */
void render(NES_State *nes) {
    if (!nes) return;

    switch (nes->ram[ADDR_RENDER_MODE]) {
        case RENDER_MODE_LEGAL_AND_TITLE:
            render_mode_legal_and_title_screens(nes);
            break;
        case RENDER_MODE_MENUS:
            render_mode_menu_screens(nes);
            break;
        case RENDER_MODE_CONGRATULATIONS:
            render_mode_congratulations_screen(nes);
            break;
        case RENDER_MODE_PLAY_AND_DEMO:
            render_mode_play_and_demo(nes);
            break;
        case RENDER_MODE_ENDING:
            render_mode_ending_animation(nes);
            break;
        default:
            break;
    }
}
